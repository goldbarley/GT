    //THis function was invalid because maps in maptable are supposed to be readonly.
    public static bool IsValidMap(int index)
    {
        return index < maps.GetLength(0);
    }

    public static bool IsValidIndex(int x, int y, MapElement[,] map)
    {
        return x >= 0 && x < map.GetLength(0) && y >= 0 && y < map.GetLength(1);
    }

    public static MapElement[,] GetMap(int index)
    {
        int rows = maps.GetLength(1);
        int cols = maps.GetLength(2);
        MapElement[,] result = new MapElement[rows, cols];

        for (int r = 0; r < rows; r++)
        {
            for (int c = 0; c < cols; c++)
            {
                result[r, c] = maps[index, r, c];
            }
        }

        return result;
    }
