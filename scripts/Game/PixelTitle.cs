    public PixelTitle() { MouseFilter = MouseFilterEnum.Ignore; }
    public override void _Draw()
    {
        string content = Caption.ToUpperInvariant();
        float glyphWidth = 6 * PixelScale;
        float x = Math.Max(0, (Size.X - Math.Max(0, content.Length * glyphWidth - PixelScale)) / 2f);
        float y = Math.Max(0, (Size.Y - 7f * PixelScale) / 2f);
        foreach (char ch in content)
        {
            if (Glyphs.TryGetValue(ch, out string[] rows))
                for (int row = 0; row < 7; row++)
                    for (int col = 0; col < 5; col++)
                        if (rows[row][col] == '1') DrawRect(new Rect2(x + col * PixelScale, y + row * PixelScale, PixelScale, PixelScale), Ink);
            x += glyphWidth;
        }
    }
